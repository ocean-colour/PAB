"""
Generate all paper figures for the PACE–Argo bbp700 matchup paper.

Runs every figure script in sequence and saves outputs to DATA_DIR
(or a custom --out-dir). Figures requiring cartopy run locally only
(global maps); all other figures work from the parquet + db.

Usage:
    python pab/matchup/make_paper_figures.py
    python pab/matchup/make_paper_figures.py --out-dir ~/Desktop/paper_figs/
    python pab/matchup/make_paper_figures.py --which scatter histogram seasonal
    python pab/matchup/make_paper_figures.py --skip maps

Available figure groups:
    scatter      Fig 4  — 1:1 bbp700 scatter with stats
    histogram    Fig 5  — distribution of δ
    geometry     Fig 3  — matchup Δt and distance histograms
    basin        Fig    — basin comparison violins
    mld          Fig    — δ vs mixed layer depth
    seasonal     Fig 11 — seasonal cycle by hemisphere
    delta_bbp    Figs 7/8 — δ vs PACE/Argo bbp (both normalizations)
    rrs700       Fig 10 — BING Rrs(700) vs δ colored by time
    chl          Fig    — Chl-a 1:1 scatter
    giop         Fig 16 — BING vs GIOP three-panel comparison
    outliers     Fig 17 — outlier case study
    maps         Figs 2,14,15 — cartopy global maps (run locally)
"""
import argparse
import sys
from pathlib import Path

from pab.config import DATA_DIR

# Default data directory — PAB stores outputs one level up from the repo
_REPO_DATA = Path(DATA_DIR)
_ALT_DATA  = Path(DATA_DIR).parent.parent / "data" / "PAB"
_DATA_DIR  = _ALT_DATA if (_ALT_DATA / "matchup_summary.parquet").exists() else _REPO_DATA

PARQUET = _DATA_DIR / "matchup_summary.parquet"
DB      = _DATA_DIR / "pab_full.db"

ALL_GROUPS = [
    "scatter", "histogram", "geometry", "basin", "mld",
    "seasonal", "delta_bbp", "rrs700", "chl", "giop", "outliers", "maps",
]


def run_analysis_figures(out_dir, which_groups):
    """Figures generated by make_analysis_figures.py."""
    from pab.matchup import make_analysis_figures as maf

    mapping = {
        "scatter":   "scatter",
        "histogram": "histogram",
        "geometry":  "dtime dist",
        "basin":     "basin",
        "mld":       "mld",
        "seasonal":  "seasonal",
    }
    wanted = [v for k, v in mapping.items() if k in which_groups]
    if not wanted:
        return
    # flatten the space-separated tokens
    tokens = []
    for w in wanted:
        tokens.extend(w.split())

    print(f"\n── Analysis figures: {tokens} ──")
    df = maf.load_data(parquet=str(PARQUET), db=str(DB))
    print(f"   Loaded {len(df):,} matchups")
    for token in tokens:
        func = getattr(maf, token, None)
        if func is None:
            print(f"   WARNING: no function '{token}' in make_analysis_figures")
            continue
        func(df, out_dir=str(out_dir))


def run_delta_vs_bbp(out_dir):
    print("\n── δ vs bbp figures (Figs 7 & 8) ──")
    from pab.matchup.plot_delta_vs_bbp import load_data, plot_pace_normalized, plot_argo_normalized
    df = load_data(parquet=str(PARQUET))
    print(f"   Loaded {len(df):,} matchups")
    plot_pace_normalized(df, out=str(out_dir))
    plot_argo_normalized(df, out=str(out_dir))


def run_rrs700(out_dir):
    print("\n── BING Rrs(700) vs δ (Fig 10) ──")
    from pab.matchup.plot_rrs700_vs_delta import load_data, make_figure
    df = load_data(db=str(DB), parquet=str(PARQUET))
    print(f"   Loaded {len(df):,} matchups with anw700")
    make_figure(df, out=str(out_dir / "fig10_rrs700_vs_delta.png"))


def run_chl(out_dir):
    print("\n── Chl-a scatter ──")
    from pab.matchup.plot_chl_matchup_scatter import load_data, make_scatter
    df = load_data(db=str(DB))
    print(f"   Loaded {len(df):,} matchups")
    make_scatter(df, out=str(out_dir / "chl_pace_vs_argo_scatter.png"))


def run_giop(out_dir):
    print("\n── BING vs GIOP comparison (Fig 16) ──")
    from pab.matchup.plot_bing_giop_comparison import load_data, make_figure
    df = load_data(db=str(DB), parquet=str(PARQUET))
    print(f"   Loaded {len(df):,} matched BING+GIOP matchups")
    make_figure(df, out=str(out_dir / "fig16_bing_giop_comparison.png"))


def run_outliers(out_dir):
    print("\n── Outlier case study (Fig 17) ──")
    from pab.matchup.plot_outlier_cases import load_data, make_figure
    df, worst, normal = load_data(db=str(DB), parquet=str(PARQUET))
    print(f"   {len(df):,} total matchups, {len(worst)} outlier cases")
    make_figure(df, worst, normal, out=str(out_dir / "fig17_outlier_cases.png"))


def run_maps(out_dir):
    print("\n── Cartopy global maps (must run locally) ──")
    print("   Run these manually:")
    print(f"   python pab/matchup/plot_bbp_matchup_map_global.py --out {out_dir}/fig2_global_map_bing.png")
    print(f"   python pab/matchup/plot_giop_matchup_map_global.py --out {out_dir}/fig14_global_map_giop.png")
    print(f"   python pab/matchup/plot_strict_matchup_map_giop.py --out {out_dir}/fig15_strict_map_giop.png")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--parquet", default=None,
                        help="Path to matchup_summary.parquet (default: auto-detect)")
    parser.add_argument("--db", default=None,
                        help="Path to pab_full.db (default: auto-detect)")
    parser.add_argument("--out-dir", default=None,
                        help="Directory to save all figures (default: DATA_DIR)")
    parser.add_argument("--which", nargs="+", choices=ALL_GROUPS,
                        default=None,
                        help="Subset of figure groups to generate (default: all)")
    parser.add_argument("--skip", nargs="+", choices=ALL_GROUPS,
                        default=None,
                        help="Figure groups to skip")
    args = parser.parse_args()

    # Allow CLI overrides of paths
    parquet = Path(args.parquet) if args.parquet else PARQUET
    db      = Path(args.db)      if args.db      else DB
    out_dir = Path(args.out_dir) if args.out_dir else (_DATA_DIR / "paper_figures")
    out_dir.mkdir(parents=True, exist_ok=True)

    groups = set(args.which or ALL_GROUPS)
    if args.skip:
        groups -= set(args.skip)

    print(f"Parquet:          {parquet}")
    print(f"Database:         {db}")
    print(f"Output directory: {out_dir}")
    print(f"Figure groups:    {sorted(groups)}\n")

    # Check required files exist
    if not parquet.exists():
        print(f"ERROR: parquet not found at {PARQUET}")
        sys.exit(1)
    if not DB.exists():
        print(f"WARNING: full database not found at {DB} — some figures will be skipped")

    # Run each group
    analysis_groups = {"scatter", "histogram", "geometry", "basin", "mld", "seasonal"}
    if groups & analysis_groups:
        try:
            run_analysis_figures(out_dir, groups & analysis_groups)
        except Exception as e:
            print(f"   ERROR in analysis figures: {e}")

    if "delta_bbp" in groups:
        try:
            run_delta_vs_bbp(out_dir)
        except Exception as e:
            print(f"   ERROR in delta_bbp: {e}")

    if "rrs700" in groups and DB.exists():
        try:
            run_rrs700(out_dir)
        except Exception as e:
            print(f"   ERROR in rrs700: {e}")

    if "chl" in groups and DB.exists():
        try:
            run_chl(out_dir)
        except Exception as e:
            print(f"   ERROR in chl: {e}")

    if "giop" in groups and DB.exists():
        try:
            run_giop(out_dir)
        except Exception as e:
            print(f"   ERROR in giop: {e}")

    if "outliers" in groups and DB.exists():
        try:
            run_outliers(out_dir)
        except Exception as e:
            print(f"   ERROR in outliers: {e}")

    if "maps" in groups:
        run_maps(out_dir)

    print("\nDone.")


if __name__ == "__main__":
    main()
